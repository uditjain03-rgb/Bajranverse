// Seals a game for its Android app: game.js is encrypted (AES-256-GCM, a fresh random key every build) into
// assets/game.bin and the readable game.js is removed from the app. The app decrypts it in memory only (never to disk)
// and serves it to its WebView. The key is written, scrambled, into a generated Java class (K.java, not in git) that R8
// then obfuscates. The same class lists the SHA-256 of the signing certificates the app accepts (CERTS env, comma
// separated hex; PLAY_CERT may add the Google Play app-signing certificate), so a re-signed (modded) copy refuses to run.
// Honest note: nothing that runs on a player's phone can be made impossible to crack; this makes copying and modding
// the game far harder than unzipping an APK.
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
export function seal(assets, javaDir, pkg) {
  const js = path.join(assets, 'game.js'), key = crypto.randomBytes(32), iv = crypto.randomBytes(12);
  const c = crypto.createCipheriv('aes-256-gcm', key, iv), enc = Buffer.concat([c.update(fs.readFileSync(js)), c.final()]);
  fs.writeFileSync(path.join(assets, 'game.bin'), Buffer.concat([iv, enc, c.getAuthTag()])); fs.rmSync(js);
  writeK(javaDir, pkg, key);
  console.log('sealed', path.join(assets, 'game.bin'), (enc.length / 1e6).toFixed(2) + ' MB');
}
// K.java: the key and the accepted certificates, each XOR-ed with a mask, so neither appears as plain bytes
export function writeK(javaDir, pkg, key) {
  const certs = [process.env.CERTS || '', process.env.PLAY_CERT || ''].join(',').split(',').map(s => s.trim().replace(/:/g, '').toLowerCase()).filter(s => /^[0-9a-f]{64}$/.test(s));
  const mask = crypto.randomBytes(64), hide = b => [...b].map((x, i) => (x ^ mask[i % 64] ^ ((i * 29 + 13) & 255)) & 255);
  const arr = a => '{' + a.join(',') + '}';
  const src = `package ${pkg};
// GENERATED by drive-src/tools/seal.mjs for every build. Do not edit and do not commit.
final class K {
  private static final int[] M = ${arr([...mask])};
  private static byte[] u(int[] a) { byte[] r = new byte[a.length]; for (int i = 0; i < a.length; i++) r[i] = (byte) (a[i] ^ M[i % 64] ^ ((i * 29 + 13) & 255)); return r; }
  static byte[] key() { ${key ? `return u(new int[]${arr(hide(key))});` : 'return null;'} }
  static byte[][] certs() { return new byte[][] { ${certs.map(h => `u(new int[]${arr(hide(Buffer.from(h, 'hex')))})`).join(', ')} }; }
}
`;
  fs.writeFileSync(path.join(javaDir, 'K.java'), src);
  console.log('K.java:', key ? 'sealed key' : 'no key (dev build)', '·', certs.length, 'accepted certificate(s)');
}
